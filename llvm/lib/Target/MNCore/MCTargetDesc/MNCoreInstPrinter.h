#ifndef LLVM_LIB_TARGET_MNCORE_MCTARGETDESC_MNCOREINSTPRINTER_H
#define LLVM_LIB_TARGET_MNCORE_MCTARGETDESC_MNCOREINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class MNCoreInstPrinter : public MCInstPrinter {
public:
  MNCoreInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                    const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  void printRegName(raw_ostream &OS, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

private:
  void printOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printOperand(const MCInst *MI, uint64_t /*Address*/, unsigned OpNum,
                    raw_ostream &O) {
    printOperand(MI, OpNum, O);
  }
  void printTagOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printImmLiteral(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  // MV instruction operand helpers (section 3.5).
  void printMVOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printMVParams(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  // L2BM / L1BM expression operand helpers (sections 3.6.7 / 3.6.8).
  void printLCOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printLBOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printDAROperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printL1BSetOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printPEOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printLB2Operand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printMABSetOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printMABDiffOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  // MAU expression operand helpers (sections 3.6.9-3.6.11).
  void printMATOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
  void printMATSideOperand(const MCInst *MI, unsigned OpNum, raw_ostream &O);
};

} // end namespace llvm

#endif // LLVM_LIB_TARGET_MNCORE_MCTARGETDESC_MNCOREINSTPRINTER_H
