//
// Emits .vsm text compatible with the MN-Core2 `assemble3` assembler.
//
// A PE instruction line consists of multiple PE instruction expressions
// separated by ';'. The instruction scheduler / packetizer marks which
// MachineInstrs belong to the same 4-cycle step by bundling them
// (isBundledWithPred). The printer walks each MachineBasicBlock, joins
// bundled expressions on one line, and emits MV instructions on their own
// lines.
//
//===----------------------------------------------------------------------===//

