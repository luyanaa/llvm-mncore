#define DEBUG_TYPE "asm-printer"

class MNCoreAsmPrinter : public AsmPrinter {
  // Printer used to render a single PE instruction expression inside a
  // bundled (';'-joined) step line. Owned here because the streamer's
  // private MCInstPrinter is not reachable from the AsmPrinter.
  std::unique_ptr<MCInstPrinter> ExprPrinter;

  // NOP steps already folded into a preceding `nop/<N>` line. The generic
  // emitter calls emitInstruction once per MachineInstr, so the run's
  // remaining NOPs are skipped here.
  SmallPtrSet<const MachineInstr *, 8> SuppressedNops;

  // One relocation record plus the kernel entry it belongs to. The Program
  // container associates a fixup with a concrete kernel, so the intermediate
  // primary key is (kernel entry, site), not the module-wide emission order:
  // a module may define several entries and each restarts its site numbering.
  struct FixupEntry {
    std::string Entry;
    unsigned Site = 0;
    mncore::RelocRecord Rec;
  };

  // Relocation records emitted so far, in `.vsm` order (kernel ABI §13).
  SmallVector<FixupEntry, 8> Fixups;

  // Kernel currently being emitted and the number of fixups it has used so
  // far (that count is the site number). Reset per function in
  // emitFunctionBodyStart().
  std::string CurrentEntry;
  unsigned CurrentEntryFixups = 0;

  // Scratch record returned by getFixup(); owned here so the pointer stays
  // valid for the duration of the emitInstruction call.
  mncore::RelocRecord ThreadLocalFixup;

public:
  static char ID;

  MNCoreAsmPrinter(TargetMachine &TM,
                   std::unique_ptr<MCStreamer> Streamer)
      : AsmPrinter(TM, std::move(Streamer), ID),
        ExprPrinter(new MNCoreInstPrinter(TM.getMCAsmInfo(),
                                          *TM.getMCInstrInfo(),
                                          TM.getMCRegisterInfo())) {}

  StringRef getPassName() const override { return "MN-Core2 Asm Printer"; }

  void emitInstruction(const MachineInstr *MI) override;
  void emitExpressionText(const MachineInstr *MI, raw_ostream &OS);
  // Check that GRF register operands satisfy the .vsm access rules that the
  // packed-immediate path enforces by construction: a longword access needs
  // a 2-aligned address (3.6.1.6/.10). SelectionDAG/RA know nothing about
  // the physical encoding, so this is the last place to catch it.
  void validateRegOperands(const MachineInstr *MI);
  // The packed relocation record carried by an `llvm.mncore.mv.reloc` line,
  // or nullptr when the MI is not a relocatable MV command.
  const mncore::RelocRecord *getFixup(const MachineInstr *MI);
  // Render an MV line followed by its `# @mncore.fixup <site>` comment and
  // record the site for the sidecar.
  void emitFixupLine(const MachineInstr *MI, const mncore::RelocRecord &R);

  bool runOnMachineFunction(MachineFunction &MF) override;

  void emitFunctionBodyStart() override;
  void emitFunctionBodyEnd() override;
  void emitEndOfAsmFile(Module &M) override;
};

void MNCoreAsmPrinter::emitFunctionBodyStart() {
  // Header comment identifying the unit. assemble3 ignores comments.
  OutStreamer->emitRawComment(
      " MN-Core2 .vsm generated by llc (straight-line kernel)");
  // A module may define more than one kernel entry. Mark each one explicitly
  // so a loader can attribute every `@mncore.fixup <site>` line to the right
  // kernel: site numbers restart at 0 per entry (kernel ABI §13.2), and the
  // sidecar records carry the entry name as half of their primary key.
  CurrentEntry = MF->getFunction().getName().str();
  CurrentEntryFixups = 0;
  OutStreamer->emitRawText("# @mncore.kernel " + CurrentEntry);
}

void MNCoreAsmPrinter::emitFunctionBodyEnd() {
  // Kernels end at end-of-file; `quit` is optional and can be inserted
  // by an explicit pass when truncation is desired.
}

// An MV line selected from `llvm.mncore.mv.reloc` carries one operand more
// than the instruction def declares: the packed relocation record. The MC
// operand list is built from all machine operands (MNCoreMCInstLower), and
// the generated printer only consumes the operands named in the asm string,
// so the extra record is invisible in the instruction text and is picked up
// here instead.
const mncore::RelocRecord *
MNCoreAsmPrinter::getFixup(const MachineInstr *MI) {
  // TSFlags[21] marks an MV command line (MNCoreInstrFormats.td); the MV
  // defs declare (params, src, dst) and nothing else, so four operands means
  // the selection came from `llvm.mncore.mv.reloc`.
  if (!((MI->getDesc().TSFlags >> 21) & 1) || MI->getNumOperands() != 4)
    return nullptr;
  const MachineOperand &MO = MI->getOperand(3);
  if (!MO.isImm() || !mncore::hasReloc((uint64_t)MO.getImm()))
    return nullptr;
  ThreadLocalFixup = mncore::unpackReloc((uint64_t)MO.getImm());
  return &ThreadLocalFixup;
}

void MNCoreAsmPrinter::emitFixupLine(const MachineInstr *MI,
                                     const mncore::RelocRecord &R) {
  unsigned Site = CurrentEntryFixups++;
  Fixups.push_back({CurrentEntry, Site, R});

  std::string ExprBuf;
  raw_string_ostream ExprOS(ExprBuf);
  emitExpressionText(MI, ExprOS);
  ExprOS.flush();

  // assemble3 ignores `#` comments; the loader keys on (kernel, site).
  std::string Line = "\t";
  Line += StringRef(ExprBuf).trim().str();
  Line += (" " + MAI.getCommentString() + " @mncore.fixup " + Twine(Site)).str();
  OutStreamer->emitRawText(Line);
}

void MNCoreAsmPrinter::emitEndOfAsmFile(Module &M) {
  // Sidecar (mncore_kernel_abi_v1.md §13.2). It is emitted as a comment
  // block so a single .vsm stream carries both the instruction text and the
  // relocation table; a loader strips the comments before assemble3 (§13.3
  // step 4). Records are grouped by kernel entry and each group restarts at
  // site 0, so the primary key is (kernel entry, site) rather than emission
  // order.
  if (Fixups.empty())
    return;
  // Raw text (not emitRawComment) so the exact bytes are fixed and testable;
  // the format is `# <indent><key>: <value>`, one field per line.
  auto emit = [&](const Twine &S) { OutStreamer->emitRawText("# " + S); };
  emit("@mncore.fixup.begin");
  bool FirstGroup = true;
  StringRef OpenEntry;
  for (const FixupEntry &F : Fixups) {
    if (FirstGroup || OpenEntry != F.Entry) {
      emit("kernel: " + F.Entry);
      emit("fixups:");
      OpenEntry = F.Entry;
      FirstGroup = false;
    }
    const mncore::RelocRecord &R = F.Rec;
    emit("  - site: " + Twine(F.Site));
    emit("    arg: " + Twine(R.Arg));
    emit(Twine("    space: ") +
         (R.Space == mncore::RelocSpace::DRAM
              ? "DRAM"
              : R.Space == mncore::RelocSpace::PDM ? "PDM" : "L2BM"));
    emit(Twine("    unit: ") +
         (R.Unit == mncore::RelocUnit::Word ? "word" : "longword"));
    emit("    addend_units: " + Twine(R.AddendUnits));
    emit("    width_bits: " + Twine(R.WidthBits));
    emit(Twine("    opcode: ") + mncore::mvOpcodeName(R.Opcode));
    emit("    operand: " + Twine(R.Operand));
  }
  emit("@mncore.fixup.end");
}

void MNCoreAsmPrinter::validateRegOperands(const MachineInstr *MI) {
  // Packed PE operands: width/alignment from the single shared decoder.
  // Only PE expressions have this operand layout (MV lines pack memory
  // kinds differently and are not PE exprs).
  if ((MI->getDesc().TSFlags & 0x1) && mncore::peAlignmentBad(*MI))
    report_fatal_error(
        Twine("MN-Core2: misaligned PE operand in ") +
        MI->getParent()->getParent()->getName() +
        " (longword needs an even address, 2-longword a multiple of 4; "
        "3.6.1.6/.10)");

  if (MI->getOpcode() == MNCore::WAIT) {
    const MachineOperand &T = MI->getOperand(MI->getNumOperands() - 1);
    if (!T.isImm() || T.getImm() == 0)
      report_fatal_error(
          "MN-Core2: `wait` requires a non-zero constant tag (3.6.13)");
  }

  const MCRegisterInfo &RI = TM.getMCRegisterInfo();
  for (const MachineOperand &MO : MI->operands()) {
    if (!MO.isReg() || !MO.getReg().isPhysical())
      continue;
    StringRef N = RI.getName(MO.getReg());
    int64_t Addr = 0;
    StringRef Digits;
    if (N.starts_with_insensitive("grf0_"))
      Digits = N.drop_front(5);
    else if (N.starts_with_insensitive("grf1_"))
      Digits = N.drop_front(5);
    else
      continue;
    if (Digits.getAsInteger(10, Addr))
      continue;
    if (Addr % 2 != 0)
      report_fatal_error(
          Twine("MN-Core2: GRF address ") + Twine(Addr) + " in " +
              MI->getParent()->getParent()->getName() +
              " is not 2-aligned; longword PE operands require an even "
              "address (3.6.1.6)");
  }
}

void MNCoreAsmPrinter::emitInstruction(const MachineInstr *MI) {
  // The packetizer marks the PE expressions that share one 4-cycle step
  // with isBundledWithPred/Succ and inserts a BUNDLE pseudo before
  // them. The MachineBasicBlock iterator the generic emitter uses
  // *skips* bundled members, so emitInstruction is only ever called on
  // the BUNDLE pseudo; we render the whole step here by walking the
  // following sibling MIs that are still "inside" the bundle and
  // joining their expression text with ';'.
  if (MI->getOpcode() == TargetOpcode::BUNDLE) {
    // Build the whole step line in memory and emit it once — the
    // streamer's emitRawText appends an end-of-line after every call,
    // so it cannot be used for intra-line separators.
    MachineBasicBlock::const_instr_iterator It =
        std::next(MI->getIterator());
    MachineBasicBlock::const_instr_iterator End = MI->getParent()->instr_end();
    std::string Line;
    raw_string_ostream OS(Line);
    bool First = true;
    while (It != End && It->isInsideBundle()) {
      validateRegOperands(&*It);
      // Each expression's generated text starts with a tab; render it to
      // a scratch buffer and strip leading whitespace so only the first
      // expression on the line keeps the conventional indent and the
      // rest are separated by "; ".
      std::string ExprBuf;
      raw_string_ostream ExprOS(ExprBuf);
      emitExpressionText(&*It, ExprOS);
      ExprOS.flush();
      StringRef ExprText = StringRef(ExprBuf).trim();
      if (!First)
        OS << "; ";
      OS << (First ? "\t" : "") << ExprText;
      First = false;
      ++It;
    }
    OS.flush();
    OutStreamer->emitRawText(StringRef(Line).rtrim());
    return;
  }

  if (!SuppressedNops.empty() && SuppressedNops.erase(MI))
    return;
  validateRegOperands(MI);

  // A relocatable MV line renders through the custom path so the sidecar
  // comment can ride on the same line. MV commands are never bundled with
  // PE expressions, so reaching here inside a bundle would mean the
  // packetizer merged an MV line, which the ISA forbids.
  if (const mncore::RelocRecord *FR = getFixup(MI)) {
    if (MI->isInsideBundle())
      report_fatal_error(
          "MN-Core2: a relocatable MV line must not be bundled");
    emitFixupLine(MI, *FR);
    return;
  }

  // Consecutive bare `nop` steps (each its own MI, never bundled: nop is
  // exclusive with every expression but wait) fold into the manual's
  // `nop/<n>` idiom. Only the first of a run emits text.
  if (MI->getOpcode() == MNCore::NOP && !MI->isInsideBundle()) {
    MachineBasicBlock::const_instr_iterator It = MI->getIterator();
    MachineBasicBlock::const_instr_iterator End = MI->getParent()->instr_end();
    unsigned N = 1;
    MachineBasicBlock::const_instr_iterator Next = std::next(It);
    while (Next != End && Next->getOpcode() == MNCore::NOP &&
           !Next->isInsideBundle()) {
      ++N;
      ++Next;
    }
    if (N > 1) {
      for (auto J = std::next(It); J != Next; ++J)
        SuppressedNops.insert(&*J);
      OutStreamer->emitRawText(Twine("\tnop/") + Twine(N));
      return;
    }
  }

  // A single (non-bundled) PE expression or an MV / pseudo line.
  MNCoreMCInstLower MCInstLowering(OutContext, *this);
  MCInst TmpInst;
  MCInstLowering.Lower(MI, TmpInst);
  EmitToStreamer(*OutStreamer, TmpInst);
}

// Render one PE instruction expression to .vsm text via the private
// MNCoreInstPrinter (the streamer's printer is not reachable).
void MNCoreAsmPrinter::emitExpressionText(const MachineInstr *MI,
                                          raw_ostream &OS) {
  MNCoreMCInstLower MCInstLowering(OutContext, *this);
  MCInst TmpInst;
  MCInstLowering.Lower(MI, TmpInst);
  ExprPrinter->printInst(&TmpInst, /*Address=*/0, /*Annot=*/"",
                         getSubtargetInfo(), OS);
}

bool MNCoreAsmPrinter::runOnMachineFunction(MachineFunction &MF) {
  AsmPrinter::runOnMachineFunction(MF);
  return false;
}

